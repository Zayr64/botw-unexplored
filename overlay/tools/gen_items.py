"""Builds overlay/source/items.inc from source/Data.cpp.

The overlay cannot compile Data.cpp: its global tables (std::string and std::map built from initializer lists)
need a stack frame of about 200 KB at start-up, more than the overlay loader gives, and the overlay crashed with a
data abort. The generated file is a plain constant table that costs no stack or heap.

Usage (from the repository root): python3 overlay/tools/gen_items.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'source' / 'Data.cpp'
TARGET = ROOT / 'overlay' / 'source' / 'items.inc'

STR = r'"((?:[^"\\]|\\.)*)"'
NUM = r'(-?[0-9.]+(?:e-?[0-9]+)?)f?'
HASH = r'([0-9]+)'
S = r'\s*,\s*'


def find(pattern, text):
    return re.findall(pattern, text)


def main():
    text = SOURCE.read_text(encoding='utf-8')
    hints = {}
    for number, hint, _image in find(r'\{\s*([0-9]+)\s*,\s*\{\s*' + STR + S + STR + r'\s*\}\s*\}', text):
        hints[int(number)] = hint

    rows = []
    koroks = find(r'Data::Korok\(\s*' + HASH + S + STR + S + NUM + S + NUM + S + r'(-?[0-9]+)\s*\)', text)
    for h, _internal, x, y, number in koroks:
        rows.append(('Korok', h, x, y, 'Korok seed', hints.get(int(number), '')))
    shrines = find(r'Data::Shrine\(\s*' + HASH + S + STR + S + NUM + S + NUM + r'\s*\)', text)
    for h, name, x, y in shrines:
        rows.append(('Shrine', h, x, y, name, ''))
    dlc = find(r'Data::DLCShrine\(\s*' + HASH + S + NUM + S + NUM + r'\s*\)', text)
    for h, x, y in dlc:
        rows.append(('DLCShrine', h, x, y, 'DLC shrine', ''))
    locations = find(r'Data::Location\(\s*' + HASH + S + STR + S + NUM + S + NUM + r'\s*\)', text)
    for h, name, x, y in locations:
        rows.append(('Location', h, x, y, name, ''))
    for kind, label in (('Hinox', 'Hinox'), ('Talus', 'Stone Talus'), ('Molduga', 'Molduga')):
        for h, x, y in find(r'Data::' + kind + r'\(\s*' + HASH + S + NUM + S + NUM + r'\s*\)', text):
            rows.append((kind, h, x, y, label, ''))

    counts = {kind: sum(1 for r in rows if r[0] == kind) for kind in
              ('Korok', 'Shrine', 'DLCShrine', 'Location', 'Hinox', 'Talus', 'Molduga')}
    expected = {'Korok': 900, 'Shrine': 120, 'DLCShrine': 16, 'Location': 187, 'Hinox': 40, 'Talus': 40, 'Molduga': 4}
    if counts != expected:
        sys.exit(f'unexpected counts: {counts}')
    missing_hints = sum(1 for r in rows if r[0] == 'Korok' and not r[5])

    out = ['// Generated by overlay/tools/gen_items.py from source/Data.cpp. Do not edit.',
           f'// {len(rows)} objects; {missing_hints} Koroks without a hint.']
    def flt(value):
        return value if ('.' in value or 'e' in value) else value + '.0'

    for kind, h, x, y, name, hint in rows:
        out.append(f'{{Data::ObjectType::{kind}, {h}u, {flt(x)}f, {flt(y)}f, "{name}", "{hint}"}},')
    TARGET.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print(f'{TARGET.relative_to(ROOT)}: {len(rows)} objects {counts}, {missing_hints} Koroks without a hint')


if __name__ == '__main__':
    main()
