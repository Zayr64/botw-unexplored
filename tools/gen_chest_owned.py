#!/usr/bin/env python3
"""Makes source/ChestOwnedData.cpp: for each item of the armor-group chests (armor, key items, horse gear), the flags
that tell the player already has it, whichever way it came (a shop, a quest, another chest).

    python3 tools/gen_chest_owned.py <romfs> > source/ChestOwnedData.cpp

The game sets IsGet_<actor> the first time an item is obtained. An armor piece is several actors, one per level of
upgrade, all with the same name: the item is had when any of them is set. The actors come from the names of
Message/Msg_USen.product.ssarc (Pack/Bootup_USen.pack), ActorType/*.msbt (<actor>_Name), matched with
ChestItemNames of source/ChestData.cpp; only CRC32 hashes of the flags go into the output. No dependencies: the
formats are read by tools/nxfmt.py.
"""
import collections
import pathlib
import re
import sys
import zlib

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import nxfmt  # noqa: E402

FORK = pathlib.Path(__file__).resolve().parent.parent


def main():
    romfs = pathlib.Path(sys.argv[1])
    boot = nxfmt.sarc((romfs / "Pack/Bootup_USen.pack").read_bytes())
    msg = nxfmt.sarc(boot["Message/Msg_USen.product.ssarc"])
    actors_by_name = collections.defaultdict(set)
    for key in msg:
        if key.startswith("ActorType/"):
            for label, text in nxfmt.msbt_texts(msg[key]).items():
                if label.endswith("_Name"):
                    actors_by_name[" ".join(text.split())].add(label[: -len("_Name")])

    source = (FORK / "source/ChestData.cpp").read_text(encoding="utf-8")
    block = source[source.index("const char* const ChestItemNames[] = {"):]
    names = re.findall(r'"((?:[^"\\]|\\.)*)"', block[: block.index("};")])
    armor = source[source.index("const Chest ArmorChests[] = {"):]
    armor = armor[: armor.index("};")]
    items = sorted({int(i) for i in re.findall(r"ChestContents::\w+\), (\d+)\}", armor)})

    rows = []
    for item in items:
        actors = sorted(actors_by_name.get(names[item], ()))
        if not actors:
            print("no actor for", names[item], file=sys.stderr)
            continue
        for actor in actors:
            rows.append((item, zlib.crc32(("IsGet_" + actor).encode()), actor))
    out = [
        "// Generated by tools/gen_chest_owned.py: the IsGet_<actor> flags of each item of the armor-group chests (every",
        "// level of an armor piece); the player has the item when any is set.",
        '#include "Chests.h"',
        "",
        "namespace Data",
        "{",
        "const ChestItemOwnFlag ChestItemOwnFlags[] = {",
    ]
    out += ["    {%d, %du}, // %s" % (item, flag, actor) for item, flag, actor in rows]
    out += ["};", "const int ChestItemOwnFlagsCount = %d;" % len(rows), "}", ""]
    sys.stdout.write("\n".join(out))
    print("items: %d, flags: %d" % (len({r[0] for r in rows}), len(rows)), file=sys.stderr)


if __name__ == "__main__":
    main()
