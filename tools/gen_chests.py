#!/usr/bin/env python3
"""Generates source/ChestData.cpp, the treasure chests of the world map.

    python3 tools/gen_chests.py <tbox.json> <names.json>

Both files come from the object map of zeldamods (https://objmap.zeldamods.org), which reads them from the
game's own map files; they are not kept in this repository:

    curl -o tbox.json 'https://radar.zeldamods.org/objs/MainField/?q=actor%3A%5E%22TBox_%22&limit=10000'
    curl -o names.json https://objmap.zeldamods.org/game_files/names.json

Every chest has a flag in the save, MainField_<actor>_<hash id>, set when it is opened; the app stores its CRC32.
A chest is "special" when it holds armor, a key item or horse gear, or a weapon, bow, shield or material
found in at most two chests of the whole map (those of Normal Mode; for a chest that only exists in Master
Mode, all of them). Arrows, gems and rupees never make one. The three chests of the gambling minigame have
no content and no flag, and are left out.
"""
import collections
import json
import pathlib
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]

# Order of Data::ChestContents in source/Chests.h.
CONTENTS = ['Weapon', 'Bow', 'Shield', 'Armor', 'Arrows', 'Mineral', 'Rupees', 'Material', 'HorseGear', 'KeyItem']


def contents_of(drop):
    if drop.startswith(('Armor_', 'Obj_Armor_')):
        return 'Armor'
    if drop.startswith('Weapon_Bow_'):
        return 'Bow'
    if drop.startswith('Weapon_Shield_'):
        return 'Shield'
    if drop.startswith('Weapon_'):
        return 'Weapon'
    if 'Arrow' in drop:
        return 'Arrows'
    if drop.startswith('Item_Ore_'):
        return 'Mineral'
    if drop.startswith('PutRupee_'):
        return 'Rupees'
    if drop.startswith('GameRomHorse'):
        return 'HorseGear'
    if drop.startswith('Obj_'):
        return 'KeyItem'
    if drop.startswith('Item_'):
        return 'Material'
    raise SystemExit(f'unknown kind of content: {drop}')


def main(tbox_path, names_path):
    objects = json.load(open(tbox_path, encoding='utf-8'))
    names = json.load(open(names_path, encoding='utf-8'))
    chests = [o for o in objects if o.get('drop') and o['drop'][1]]
    skipped = len(objects) - len(chests)

    # How many chests hold each item: in Normal Mode, and in Master Mode (which has all of them).
    in_normal_mode = collections.Counter(o['drop'][1] for o in chests if not o.get('hard_mode'))
    in_master_mode = collections.Counter(o['drop'][1] for o in chests)

    def is_special(o):
        drop = o['drop'][1]
        kind = contents_of(drop)
        if kind in ('Armor', 'KeyItem', 'HorseGear'):
            return True
        count = (in_master_mode if o.get('hard_mode') else in_normal_mode)[drop]
        return kind in ('Weapon', 'Bow', 'Shield', 'Material') and count <= 2

    items = sorted({o['drop'][1] for o in chests}, key=lambda drop: names[drop])
    item_index = {drop: i for i, drop in enumerate(items)}

    rows = {False: [], True: []}
    seen = set()
    for o in chests:
        drop = o['drop'][1]
        flag = f"MainField_{o['name']}_{o['hash_id']}"
        crc = zlib.crc32(flag.encode()) & 0xFFFFFFFF
        assert crc not in seen, f'two chests with the flag hash of {flag}'
        seen.add(crc)
        flags = []
        if o.get('hard_mode'):
            flags.append('ChestMasterModeOnly')
        if 'Aoc' in o['name']:
            flags.append('ChestDlc')
        if o['name'] == 'TBox_Field_Enemy':
            flags.append('ChestEnemyCamp')
        if 'Collabo' in o['name']:
            flags.append('ChestSideQuest')
        rows[is_special(o)].append(
            (crc, f"    {{{crc}u, {o['pos'][0]:.2f}f, {o['pos'][2]:.2f}f, {' | '.join(flags) or '0'}, "
                  f"static_cast<uint8_t>(ChestContents::{contents_of(drop)}), {item_index[drop]}}},"))

    out = [
        '// Generated by tools/gen_chests.py from the object map of zeldamods. Do not edit.',
        f'// {len(rows[False])} chests and {len(rows[True])} special chests; {skipped} without content left out.',
        '#include "Chests.h"',
        '',
        'namespace Data',
        '{',
    ]
    for special, name in ((False, 'Chests'), (True, 'SpecialChests')):
        out.append(f'const Chest {name}[] = {{')
        out.extend(line for _, line in sorted(rows[special]))
        out.append('};')
        out.append(f'const int {name}Count = sizeof({name}) / sizeof({name}[0]);')
        out.append('')
    out.append('const char* const ChestItemNames[] = {')
    for drop in items:
        display = names[drop].replace('\\', '\\\\').replace('"', '\\"')
        out.append(f'    "{display}",')
    out.append('};')
    out.append('const int ChestItemNamesCount = sizeof(ChestItemNames) / sizeof(ChestItemNames[0]);')
    out.append('}')
    (ROOT / 'source' / 'ChestData.cpp').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')

    normal = [o for o in chests if not o.get('hard_mode')]
    print(f'{len(rows[False])} chests + {len(rows[True])} special; {len(items)} items; '
          f'{len(normal)} in Normal Mode, of which {sum(1 for o in normal if is_special(o))} special '
          f'({sum(1 for o in normal if is_special(o) and "Aoc" in o["name"])} of the DLC)')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
