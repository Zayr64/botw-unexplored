#!/usr/bin/env python3
"""Generates source/WallData.cpp, the walls of the world map that a bomb breaks open.

    curl -o walls.json 'https://radar.zeldamods.org/objs/MainField/?q=actor%3A%5E%22WallCrack%22&limit=1000'
    python3 tools/gen_walls.py walls.json

The list comes from the object map of zeldamods (https://objmap.zeldamods.org), which reads it from the game's
own map files; it is not kept in this repository. Each wall has a flag in the save, MainField_WallCrack_<hash id>,
set when it is broken; the app stores its CRC32. The flag is kept: on two saves twelve hours of play apart the
walls broken in the first were still set in the second, while crates, plants and enemies had all gone back to
zero at a Blood Moon.
"""
import json
import pathlib
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]


def main(path):
    objects = [o for o in json.load(open(path, encoding='utf-8')) if o['name'] == 'WallCrack']
    rows = []
    seen = set()
    for o in objects:
        crc = zlib.crc32(f"MainField_WallCrack_{o['hash_id']}".encode()) & 0xFFFFFFFF
        assert crc not in seen, 'two walls with the same flag hash'
        seen.add(crc)
        rows.append((crc, f"    {{{crc}u, {o['pos'][0]:.2f}f, {o['pos'][2]:.2f}f}},"))
    out = [
        '// Generated by tools/gen_walls.py from the object map of zeldamods. Do not edit.',
        f'// {len(rows)} breakable walls.',
        '#include "Walls.h"',
        '',
        'namespace Data',
        '{',
        'const Wall Walls[] = {',
    ]
    out.extend(line for _, line in sorted(rows))
    out.append('};')
    out.append('const int WallsCount = sizeof(Walls) / sizeof(Walls[0]);')
    out.append('}')
    (ROOT / 'source' / 'WallData.cpp').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(rows)} breakable walls; only in Master Mode: {sum(1 for o in objects if o.get("hard_mode"))}')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
