#!/usr/bin/env python3
"""Generates source/ShrineChestData.cpp, the treasure chests inside each shrine.

    python3 tools/gen_shrine_chests.py --download shrine-chests.json
    python3 tools/gen_shrine_chests.py shrine-chests.json

The first command asks the object map of zeldamods (https://objmap.zeldamods.org) for the chests of each
shrine map, CDungeon/Dungeon000 to Dungeon135, one request per shrine, and keeps the answers in a file that is
not part of this repository. The second one writes the table.

Every chest has a flag in the save, CDungeon_<actor>_<hash id>, set when it is opened; the app stores its
CRC32, grouped by shrine. The shrine is named by the CRC32 of its discovery flag, Location_DungeonNNN, the
hash the rest of the app knows it by.
"""
import json
import pathlib
import sys
import time
import urllib.request
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SHRINE_MAPS = 136  # 120 shrines and the 16 of the Champions' Ballad


def crc(name):
    return zlib.crc32(name.encode()) & 0xFFFFFFFF


def download(path):
    answers = {}
    for number in range(SHRINE_MAPS):
        name = f'Dungeon{number:03d}'
        url = f'https://radar.zeldamods.org/objs/CDungeon/{name}?q=actor%3A%5E%22TBox_%22&limit=200'
        request = urllib.request.Request(url, headers={'User-Agent': 'gen_shrine_chests'})
        with urllib.request.urlopen(request, timeout=60) as response:
            answers[name] = json.load(response)
        time.sleep(0.15)
    pathlib.Path(path).write_text(json.dumps(answers), encoding='utf-8')
    print(f'{sum(len(chests) for chests in answers.values())} chests of {len(answers)} shrines in {path}')


def generate(path):
    answers = json.loads(pathlib.Path(path).read_text(encoding='utf-8'))
    shrines = []
    seen = set()
    for name in sorted(answers):
        chests = answers[name]
        if not chests:
            continue
        flags = sorted(crc(f"CDungeon_{chest['name']}_{chest['hash_id']}") for chest in chests)
        assert not seen.intersection(flags) and len(set(flags)) == len(flags), f'repeated chest flag in {name}'
        seen.update(flags)
        shrines.append((crc(f'Location_{name}'), name, flags))
    shrines.sort()
    assert len({location for location, _, _ in shrines}) == len(shrines)

    out = [
        '// Generated by tools/gen_shrine_chests.py from the object map of zeldamods. Do not edit.',
        f'// {len(seen)} chests in {len(shrines)} shrines.',
        '#include "ShrineChests.h"',
        '',
        'namespace Data',
        '{',
        'const uint32_t ShrineChestFlags[] = {',
    ]
    lists = []
    first = 0
    for location, name, flags in shrines:
        out.append('    ' + ' '.join(f'{flag}u,' for flag in flags) + f' // {name}')
        lists.append(f'    {{{location}u, {first}, {len(flags)}}}, // {name}')
        first += len(flags)
    out.append('};')
    out.append('const int ShrineChestFlagsCount = sizeof(ShrineChestFlags) / sizeof(ShrineChestFlags[0]);')
    out.append('')
    out.append('const ShrineChestList ShrineChestLists[] = {')
    out.extend(lists)
    out.append('};')
    out.append('const int ShrineChestListsCount = sizeof(ShrineChestLists) / sizeof(ShrineChestLists[0]);')
    out.append('}')
    (ROOT / 'source' / 'ShrineChestData.cpp').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(seen)} chests in {len(shrines)} shrines; the most in one shrine: {max(len(f) for _, _, f in shrines)}')


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == '--download':
        download(sys.argv[2])
    elif len(sys.argv) == 2:
        generate(sys.argv[1])
    else:
        raise SystemExit(__doc__)
