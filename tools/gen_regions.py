#!/usr/bin/env python3
"""Generates source/RegionData.cpp: the region of the map each object of the app is in.

    curl -o MapTower.json https://objmap.zeldamods.org/game_files/ecosystem/MapTower.json
    python3 tools/gen_regions.py MapTower.json

MapTower.json, from the object map of zeldamods, has the outline of the fifteen regions of the map, the areas
each tower reveals, in game coordinates and in the order of the towers (MapTower_01 to _15). It is not kept in
this repository. The app does not carry the outlines: this script works out, once, which region every Korok,
shrine, location, miniboss, chest and wall is in (they are read from the sources of the app), and writes that
table and the bounding box of each region.

Run it again after any of the tables it reads changes (Data.cpp, ChestData.cpp, WallData.cpp).
"""
import json
import pathlib
import re
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
REGIONS = 15


def crc(name):
    return zlib.crc32(name.encode()) & 0xFFFFFFFF


def in_ring(x, z, ring):
    hit = False
    j = len(ring) - 1
    for i in range(len(ring)):
        xi, zi = ring[i]
        xj, zj = ring[j]
        if (zi > z) != (zj > z) and x < (xj - xi) * (z - zi) / (zj - zi) + xi:
            hit = not hit
        j = i
    return hit


def in_polygon(x, z, polygon):
    rings = polygon['coordinates']
    return in_ring(x, z, rings[0]) and not any(in_ring(x, z, hole) for hole in rings[1:])


def main(path):
    outlines = json.load(open(path, encoding='utf-8'))
    assert sorted(int(k) for k in outlines) == list(range(REGIONS))

    def region_of(x, z):
        found = [int(k) for k, polygons in outlines.items() if any(in_polygon(x, z, p) for p in polygons)]
        assert len(found) == 1, f'({x}, {z}) is in {len(found)} regions'
        return found[0]

    objects = {}  # flag hash -> (x, z)
    data = (ROOT / 'source' / 'Data.cpp').read_text(encoding='utf-8')
    for kind in ('Korok', 'Shrine', 'DLCShrine', 'Location', 'Hinox', 'Talus', 'Molduga'):
        for m in re.finditer(r'Data::%s\((\d+),(?: "[^"]*",)? (-?[\d.]+)f?, (-?[\d.]+)f?' % kind, data):
            assert int(m.group(1)) not in objects, 'two objects with the same hash'
            objects[int(m.group(1))] = (float(m.group(2)), float(m.group(3)))
    for name in ('ChestData.cpp', 'WallData.cpp'):
        for m in re.finditer(r'\{(\d+)u, (-?[\d.]+)f, (-?[\d.]+)f', (ROOT / 'source' / name).read_text(encoding='utf-8')):
            assert int(m.group(1)) not in objects, 'two objects with the same hash'
            objects[int(m.group(1))] = (float(m.group(2)), float(m.group(3)))

    regions = {h: region_of(x, z) for h, (x, z) in objects.items()}
    # The order of the outlines is the order of the towers: each tower stands in its own region.
    for number in range(1, REGIONS + 1):
        tower = crc(f'Location_MapTower{number:02d}')
        assert regions[tower] == number - 1, f'tower {number} is in region {regions[tower]}'

    out = [
        '// Generated by tools/gen_regions.py from the object map of zeldamods. Do not edit.',
        f'// {len(regions)} objects in {REGIONS} regions.',
        '#include "Regions.h"',
        '',
        'namespace Data',
        '{',
        'const RegionEntry RegionEntries[] = {',
    ]
    entries = sorted(regions.items())
    for i in range(0, len(entries), 6):
        out.append('    ' + ' '.join(f'{{{h}u, {r}}},' for h, r in entries[i:i + 6]))
    out.append('};')
    out.append('const int RegionEntriesCount = sizeof(RegionEntries) / sizeof(RegionEntries[0]);')
    out.append('')
    out.append('// minX, minZ, maxX, maxZ of each region, in game coordinates')
    out.append('const RegionBounds RegionBoundsList[] = {')
    for region in range(REGIONS):
        xs = [pt[0] for p in outlines[str(region)] for pt in p['coordinates'][0]]
        zs = [pt[1] for p in outlines[str(region)] for pt in p['coordinates'][0]]
        out.append(f'    {{{min(xs):.1f}f, {min(zs):.1f}f, {max(xs):.1f}f, {max(zs):.1f}f}},')
    out.append('};')
    out.append('}')
    (ROOT / 'source' / 'RegionData.cpp').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    sizes = [sum(1 for r in regions.values() if r == region) for region in range(REGIONS)]
    print(f'{len(regions)} objects in {REGIONS} regions; from {min(sizes)} to {max(sizes)} in each')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
